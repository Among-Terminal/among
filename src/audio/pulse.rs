//! Private libpulse client configuration for the decoder helper.
//!
//! The helper must not hand its audio to a PulseAudio server through shared
//! memory. PulseAudio 16.1 and 17.0 race when a shared-memory client
//! disconnects while another client records the sink monitor: the sink IO
//! thread lowers the imported-block count in `memblock_free` before taking the
//! import mutex, while the main thread tears down the client's import table
//! under that mutex and asserts the count is positive. The server then aborts
//! (`memblock.c:780`) and every application loses sound. The helper disconnects
//! after each sound, and immediately on cancellation, so it would hit that
//! window. Without shared memory the server copies the data into its own pool,
//! keeps no imported blocks for the helper and the teardown has nothing to race
//! on. Notification sounds are a few hundred kilobytes, so copying costs
//! nothing measurable.
//!
//! The only way to switch it off in a pulsesink client is a client.conf: the
//! context is created without a property list, and `PULSE_PROP` is applied only
//! after the memory pool type is fixed. Pointing `PULSE_CLIENTCONFIG` at a
//! private file would drop the user's own client settings (default server,
//! cookie, sink), so the file first `.include`s the configuration libpulse
//! itself would have read, in libpulse's lookup order, and only then disables
//! shared memory. A later assignment wins in libpulse's parser.

use std::ffi::OsString;
use std::fs;
use std::io::{self, Write};
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};

/// libpulse's compiled-in system configuration on Debian, Ubuntu and Fedora,
/// and in the libpulse the Snap and AppImage carry.
const SYSTEM_CLIENT_CONFIG: &str = "/etc/pulse/client.conf";
const FILE_NAME: &str = "client.conf";

/// What libpulse consults to find the client configuration.
pub(crate) struct Lookup {
    /// `PULSE_CLIENTCONFIG` from Among's own environment.
    pub(crate) client_config: Option<OsString>,
    /// `PULSE_CONFIG_PATH` from Among's own environment.
    pub(crate) config_path: Option<OsString>,
    /// `$HOME`, or the account's home directory when it is unset.
    pub(crate) home: Option<PathBuf>,
    pub(crate) system: PathBuf,
}

impl Lookup {
    pub(crate) fn current() -> Self {
        Self {
            client_config: std::env::var_os("PULSE_CLIENTCONFIG"),
            config_path: std::env::var_os("PULSE_CONFIG_PATH"),
            home: std::env::home_dir(),
            system: PathBuf::from(SYSTEM_CLIENT_CONFIG),
        }
    }
}

enum Probe {
    Found,
    Missing,
    Unreadable,
}

fn probe(path: &Path) -> Probe {
    match fs::File::open(path) {
        Ok(file) if file.metadata().is_ok_and(|metadata| metadata.is_file()) => Probe::Found,
        Ok(_) => Probe::Unreadable,
        Err(error) if error.kind() == io::ErrorKind::NotFound => Probe::Missing,
        Err(_) => Probe::Unreadable,
    }
}

/// The client.conf libpulse would open (`pa_open_config_file`): an explicit
/// `PULSE_CLIENTCONFIG` is used or nothing is; a missing per-user file falls
/// back to the next candidate, an unreadable one stops the search.
fn user_config(lookup: &Lookup) -> Option<PathBuf> {
    if let Some(file) = &lookup.client_config {
        let file = PathBuf::from(file);
        return matches!(probe(&file), Probe::Found).then_some(file);
    }
    let local = match (&lookup.config_path, &lookup.home) {
        (Some(directory), _) => vec![PathBuf::from(directory).join(FILE_NAME)],
        (None, Some(home)) => vec![
            home.join(".pulse").join(FILE_NAME),
            home.join(".config/pulse").join(FILE_NAME),
        ],
        (None, None) => return None,
    };
    for candidate in local {
        match probe(&candidate) {
            Probe::Found => return Some(candidate),
            Probe::Missing => {}
            Probe::Unreadable => return None,
        }
    }
    matches!(probe(&lookup.system), Probe::Found).then(|| lookup.system.clone())
}

/// A path the parser can take after `.include`: it strips surrounding blanks
/// and cuts the line at `#` or `;`, so such a path cannot be expressed.
fn includable(path: &Path) -> Option<String> {
    let text = path.to_str()?;
    let expressible =
        path.is_absolute() && !text.contains(['#', ';', '\n', '\r']) && text.trim() == text;
    expressible.then(|| text.to_string())
}

/// Text of the private client.conf.
pub(crate) fn client_config(lookup: &Lookup) -> String {
    let mut text =
        String::from("# Generated by Among for its audio helper; removed with the helper.\n");
    if let Some(file) = user_config(lookup) {
        let mut files = vec![file.clone()];
        // libpulse also reads FILE.d/*.conf in byte order after FILE itself.
        let mut extra = fs::read_dir(PathBuf::from(format!("{}.d", file.display())))
            .map(|entries| {
                entries
                    .filter_map(Result::ok)
                    .map(|entry| entry.path())
                    .filter(|path| {
                        path.file_name()
                            .and_then(|name| name.to_str())
                            .is_some_and(|name| name.ends_with(".conf"))
                            && matches!(probe(path), Probe::Found)
                    })
                    .collect::<Vec<_>>()
            })
            .unwrap_or_default();
        extra.sort_by(|a, b| {
            a.as_os_str()
                .as_encoded_bytes()
                .cmp(b.as_os_str().as_encoded_bytes())
        });
        files.extend(extra);
        for file in files {
            match includable(&file) {
                Some(path) => text.push_str(&format!(".include {path}\n")),
                None => text.push_str(
                    "# A user client.conf path could not be expressed for .include and is skipped.\n",
                ),
            }
        }
    }
    text.push_str("enable-shm = no\n");
    text
}

/// Writes the private client.conf into the helper's own temporary directory
/// and returns its path for `PULSE_CLIENTCONFIG`.
pub(crate) fn write_client_config(directory: &Path, lookup: &Lookup) -> io::Result<PathBuf> {
    let path = directory.join("pulse-client.conf");
    let mut file = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(&path)?;
    file.write_all(client_config(lookup).as_bytes())?;
    file.sync_all()?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(name: &str) -> PathBuf {
        let root =
            std::env::temp_dir().join(format!("among-pulse-config-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(&root).unwrap();
        root
    }

    fn lookup(root: &Path) -> Lookup {
        Lookup {
            client_config: None,
            config_path: None,
            home: Some(root.join("home")),
            system: root.join("etc/client.conf"),
        }
    }

    fn write(path: &Path, text: &str) {
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, text).unwrap();
    }

    // Without the final line the helper would negotiate shared memory and a
    // PulseAudio server recording its sink monitor could abort on disconnect.
    #[test]
    fn shared_memory_is_disabled_after_every_user_setting() {
        let root = scratch("order");
        let user = root.join("home/.config/pulse/client.conf");
        write(&user, "enable-shm = yes\n");
        write(&root.join("home/.config/pulse/client.conf.d/20-b.conf"), "");
        write(&root.join("home/.config/pulse/client.conf.d/10-a.conf"), "");
        write(&root.join("home/.config/pulse/client.conf.d/notes.txt"), "");
        let text = client_config(&lookup(&root));
        let lines: Vec<_> = text.lines().filter(|line| !line.starts_with('#')).collect();
        assert_eq!(
            lines,
            [
                format!(".include {}", user.display()),
                format!(".include {}.d/10-a.conf", user.display()),
                format!(".include {}.d/20-b.conf", user.display()),
                "enable-shm = no".to_string(),
            ]
        );
        fs::remove_dir_all(root).unwrap();
    }

    // libpulse reads only the first existing file: legacy ~/.pulse wins over
    // ~/.config/pulse, and the system file is used only without a user file.
    #[test]
    fn the_same_single_file_as_libpulse_is_included() {
        let root = scratch("lookup");
        let system = root.join("etc/client.conf");
        write(&system, "");
        assert!(client_config(&lookup(&root)).contains(&format!(".include {}\n", system.display())));
        let modern = root.join("home/.config/pulse/client.conf");
        write(&modern, "");
        let text = client_config(&lookup(&root));
        assert!(text.contains(&format!(".include {}\n", modern.display())));
        assert!(!text.contains(&system.display().to_string()));
        let legacy = root.join("home/.pulse/client.conf");
        write(&legacy, "");
        let text = client_config(&lookup(&root));
        assert!(text.contains(&format!(".include {}\n", legacy.display())));
        assert!(!text.contains(&modern.display().to_string()));
        fs::remove_dir_all(root).unwrap();
    }

    // An explicit PULSE_CLIENTCONFIG replaces the search entirely, also when
    // it names a missing file; PULSE_CONFIG_PATH replaces the home lookup.
    #[test]
    fn environment_overrides_follow_libpulse() {
        let root = scratch("environment");
        write(&root.join("etc/client.conf"), "");
        write(&root.join("home/.config/pulse/client.conf"), "");
        let explicit = root.join("explicit.conf");
        let mut with_env = lookup(&root);
        with_env.client_config = Some(explicit.clone().into_os_string());
        assert_eq!(client_config(&with_env).matches(".include").count(), 0);
        write(&explicit, "");
        assert!(client_config(&with_env).contains(&format!(".include {}\n", explicit.display())));
        let mut with_path = lookup(&root);
        let directory = root.join("custom");
        with_path.config_path = Some(directory.clone().into_os_string());
        write(&directory.join("client.conf"), "");
        let text = client_config(&with_path);
        assert!(text.contains(&format!(".include {}/client.conf\n", directory.display())));
        assert_eq!(text.matches(".include").count(), 1);
        fs::remove_dir_all(root).unwrap();
    }

    // Real libpulse must still read the user's own client.conf through the
    // private file: here its default-server is the only way libpulse can learn
    // the marker address it then tries to connect to.
    #[test]
    #[ignore = "requires /usr/bin/pactl (pulseaudio-utils); the CI native job installs it"]
    fn libpulse_reads_user_settings_through_the_private_file() {
        let root = scratch("libpulse");
        let marker = root.join("no-server-here/native");
        write(
            &root.join("home/.config/pulse/client.conf"),
            &format!(
                "default-server = unix:{}\nautospawn = no\n",
                marker.display()
            ),
        );
        let private = root.join("private");
        fs::create_dir(&private).unwrap();
        let config = write_client_config(&private, &lookup(&root)).unwrap();
        let output = std::process::Command::new("/usr/bin/pactl")
            .arg("info")
            .env_clear()
            .env("HOME", root.join("home"))
            .env("XDG_RUNTIME_DIR", &private)
            .env("PULSE_CLIENTCONFIG", &config)
            .env("PULSE_LOG", "4")
            .output()
            .unwrap();
        let log = String::from_utf8_lossy(&output.stderr);
        assert!(!output.status.success(), "no server exists at the marker");
        assert!(
            log.contains(&format!("unix:{}", marker.display())),
            "libpulse did not use the included default-server:\n{log}"
        );
        fs::remove_dir_all(root).unwrap();
    }

    // The parser cuts a line at '#' or ';', so including such a path would
    // read a different, possibly attacker-chosen, file.
    #[test]
    fn inexpressible_paths_are_skipped_not_truncated() {
        let root = scratch("comment");
        let user = root.join("home#x/.config/pulse/client.conf");
        write(&user, "");
        let mut paths = lookup(&root);
        paths.home = Some(root.join("home#x"));
        let text = client_config(&paths);
        assert!(!text.lines().any(|line| line.starts_with(".include")));
        assert!(text.ends_with("enable-shm = no\n"));
        fs::remove_dir_all(root).unwrap();
    }
}

//! AppImage assembly: what the build refuses and what a real build yields.
//!
//! The synthetic tests pin the refusals that guard users: a launcher that
//! leaks GTK paths into their shells, an image missing the data the app needs
//! to start, and a library nobody can name a licence or source for. The real
//! build test runs the pinned helpers and is enabled only where the workflow
//! provides staged inputs; elsewhere it says that it did not run.

use among_tools::{appimage_build, storage, Result};
use serde_json::Value;
use std::{
    collections::BTreeMap,
    fs,
    os::unix::fs::PermissionsExt,
    path::{Path, PathBuf},
    process::Command,
};

const ELF: &[u8] = b"\x7fELF\x02\x01synthetic library stand-in";

fn scratch(prefix: &str) -> Result<PathBuf> {
    storage::private_directory(&std::env::temp_dir(), prefix)
}

fn write(root: &Path, relative: &str, bytes: &[u8]) -> Result<()> {
    let path = root.join(relative);
    fs::create_dir_all(path.parent().ok_or("fixture has no parent")?)?;
    fs::write(path, bytes)?;
    Ok(())
}

fn complete_runtime_data(root: &Path) -> Result<()> {
    for relative in [
        "usr/share/glib-2.0/schemas/gschemas.compiled",
        "usr/share/glib-2.0/schemas/org.gnome.desktop.interface.gschema.xml",
        "usr/share/mime/mime.cache",
        "usr/share/icons/Adwaita/index.theme",
    ] {
        write(root, relative, b"synthetic data")?;
    }
    write(
        root,
        "usr/lib/gdk-pixbuf-2.0/2.10.0/loaders.cache",
        b"\"libpixbufloader-svg.so\"\n\"svg\" 6 \"gdk-pixbuf\"\n",
    )
}

#[test]
fn missing_schemas_mime_cache_or_svg_loader_fails_the_build() -> Result<()> {
    let root = scratch("among-appimage-runtime-data")?;
    complete_runtime_data(&root)?;
    appimage_build::require_runtime_data(&root)?;
    for relative in [
        "usr/share/glib-2.0/schemas/gschemas.compiled",
        "usr/share/glib-2.0/schemas/org.gnome.desktop.interface.gschema.xml",
        "usr/share/mime/mime.cache",
        "usr/lib/gdk-pixbuf-2.0/2.10.0/loaders.cache",
        "usr/share/icons/Adwaita/index.theme",
    ] {
        let path = root.join(relative);
        let bytes = fs::read(&path)?;
        fs::remove_file(&path)?;
        let error = appimage_build::require_runtime_data(&root)
            .err()
            .ok_or("build accepted a payload without required runtime data")?;
        assert!(error.to_string().contains(relative), "{error}");
        fs::write(&path, b"")?;
        assert!(appimage_build::require_runtime_data(&root).is_err());
        fs::remove_file(&path)?;
        std::os::unix::fs::symlink("/etc/hostname", &path)?;
        assert!(appimage_build::require_runtime_data(&root).is_err());
        fs::remove_file(&path)?;
        fs::write(&path, bytes)?;
    }
    write(
        &root,
        "usr/lib/gdk-pixbuf-2.0/2.10.0/loaders.cache",
        b"\"libpixbufloader-png.so\"\n",
    )?;
    assert!(appimage_build::require_runtime_data(&root).is_err());
    fs::remove_dir_all(root)?;
    Ok(())
}

#[test]
fn linuxdeploy_wrapper_and_gtk_hooks_are_removed_and_the_reviewed_launcher_restored() -> Result<()>
{
    let root = scratch("among-appimage-launcher")?;
    let launcher = b"reviewed launcher bytes";
    let digest = storage::sha256(launcher.as_slice())?;
    let wrapper = b"#! /usr/bin/env bash\n\n# autogenerated by linuxdeploy\nsource \"$this_dir\"/apprun-hooks/\"linuxdeploy-plugin-gtk.sh\"\nexec \"$this_dir\"/AppRun.wrapped \"$@\"\n";
    let deployed = |root: &Path| -> Result<()> {
        write(root, "AppRun", wrapper)?;
        write(root, "AppRun.wrapped", launcher)?;
        write(
            root,
            "apprun-hooks/linuxdeploy-plugin-gtk.sh",
            b"export GSETTINGS_SCHEMA_DIR=\"$APPDIR/usr/share/glib-2.0/schemas\"\n",
        )
    };
    deployed(&root)?;
    appimage_build::restore_launcher(&root, &digest)?;
    assert_eq!(fs::read(root.join("AppRun"))?, launcher);
    assert!(!root.join("AppRun.wrapped").exists() && !root.join("apprun-hooks").exists());
    // Already restored: the exact launcher alone is accepted again.
    appimage_build::restore_launcher(&root, &digest)?;

    // A launcher that is not the reviewed one is refused even when unwrapped.
    assert!(appimage_build::restore_launcher(&root, &"0".repeat(64)).is_err());

    // Hooks without the wrapper would mean an unknown layout.
    write(&root, "apprun-hooks/other.sh", b"export X=1\n")?;
    assert!(appimage_build::restore_launcher(&root, &digest).is_err());
    fs::remove_dir_all(root.join("apprun-hooks"))?;

    // A wrapped file next to a launcher that is not linuxdeploy's wrapper.
    write(&root, "AppRun.wrapped", launcher)?;
    assert!(appimage_build::restore_launcher(&root, &digest).is_err());
    fs::remove_file(root.join("AppRun.wrapped"))?;

    // A hook directory holding something other than shell hooks.
    deployed(&root)?;
    write(&root, "apprun-hooks/binary", ELF)?;
    assert!(appimage_build::restore_launcher(&root, &digest).is_err());
    fs::remove_dir_all(root)?;
    Ok(())
}

#[test]
fn an_unattributed_bundled_library_fails_the_audit_by_name() -> Result<()> {
    let root = scratch("among-appimage-audit")?;
    for relative in [
        "AppRun",
        "usr/bin/among",
        "usr/share/among/plugins/clock",
        "usr/lib/libgtk-4.so.1",
        "usr/lib/gdk-pixbuf-2.0/2.10.0/loaders/libpixbufloader-svg.so",
    ] {
        write(&root, relative, ELF)?;
    }
    write(
        &root,
        "usr/share/doc/among-terminal/LICENSE",
        b"text, not ELF",
    )?;
    std::os::unix::fs::symlink(
        "gdk-pixbuf-2.0/2.10.0/loaders/libpixbufloader-svg.so",
        root.join("usr/lib/libpixbufloader-svg.so"),
    )?;
    let libraries = appimage_build::bundled_libraries(&root)?;
    assert_eq!(
        libraries.keys().cloned().collect::<Vec<_>>(),
        vec![
            "usr/lib/gdk-pixbuf-2.0/2.10.0/loaders/libpixbufloader-svg.so".to_string(),
            "usr/lib/libgtk-4.so.1".into()
        ]
    );
    let owners = BTreeMap::from([(
        "libgtk-4.so.1",
        appimage_build::Owner {
            package: "libgtk-4-1".into(),
            architecture: "amd64".into(),
            version: "4.14.5+ds-0ubuntu0.1".into(),
            source_package: "gtk4".into(),
            source_version: "4.14.5+ds-0ubuntu0.1".into(),
        },
    )]);
    let mut lookup = |relative: &str| Ok(owners.get(relative).cloned());
    let error = appimage_build::attribute(&libraries, &mut lookup)
        .err()
        .ok_or("audit accepted an unattributed library")?;
    assert!(
        error.to_string().contains("libpixbufloader-svg.so"),
        "{error}"
    );
    let mut everything = |_: &str| Ok(owners.get("libgtk-4.so.1").cloned());
    let records = appimage_build::attribute(&libraries, &mut everything)?;
    assert_eq!(records.len(), 2);
    assert_eq!(
        records[1]["copyright"],
        "usr/share/doc/libgtk-4-1/copyright"
    );

    // A link that leaves the payload or an ELF outside usr/lib is refused.
    std::os::unix::fs::symlink("/usr/lib", root.join("usr/lib/escape"))?;
    assert!(appimage_build::bundled_libraries(&root).is_err());
    fs::remove_file(root.join("usr/lib/escape"))?;
    write(&root, "usr/share/stray.so", ELF)?;
    assert!(appimage_build::bundled_libraries(&root).is_err());
    fs::remove_dir_all(root)?;
    Ok(())
}

/// Staged inputs for the real build, set by `appimage-release.yml` inside the
/// Ubuntu 24.04 build container. Absent elsewhere, so the test says it skipped.
fn real_inputs() -> Option<(PathBuf, PathBuf, String, String)> {
    let staged = std::env::var_os("AMONG_APPIMAGE_STAGED").map(PathBuf::from)?;
    let tools = std::env::var_os("AMONG_APPIMAGE_TOOLS").map(PathBuf::from)?;
    let architecture = std::env::var("AMONG_APPIMAGE_ARCH").ok()?;
    let version = std::env::var("AMONG_APPIMAGE_VERSION").ok()?;
    Some((staged, tools, architecture, version))
}

#[test]
fn real_pinned_helpers_build_an_audited_appimage_and_refuse_existing_output() -> Result<()> {
    let Some((staged, tools, architecture, version)) = real_inputs() else {
        println!("SKIPPED: AMONG_APPIMAGE_STAGED/TOOLS/ARCH/VERSION not set; the real AppImage build runs in appimage-release.yml");
        return Ok(());
    };
    let root = scratch("among-appimage-real-build")?;
    let output = root.join("candidate");
    let build = |output: &Path| {
        Command::new(env!("CARGO_BIN_EXE_among-tools"))
            .args(["build-appimage"])
            .arg(&staged)
            .arg(&tools)
            .args([&architecture, &version])
            .arg(output)
            .output()
    };
    let first = build(&output)?;
    assert!(
        first.status.success(),
        "{}",
        String::from_utf8_lossy(&first.stderr)
    );
    let name = appimage_build::file_name(&version, &architecture)?;
    let mut members = fs::read_dir(&output)?
        .map(|entry| entry.map(|entry| entry.file_name().to_string_lossy().into_owned()))
        .collect::<std::io::Result<Vec<_>>>()?;
    members.sort();
    let audit_name = format!("among-{version}-{architecture}.audit.json");
    let mut expected = vec!["SHA256SUMS".to_string(), audit_name.clone(), name.clone()];
    expected.sort();
    assert_eq!(members, expected);
    let image = output.join(&name);
    assert_ne!(image.metadata()?.permissions().mode() & 0o111, 0);
    let digest = storage::sha256(fs::File::open(&image)?)?;
    assert_eq!(
        fs::read_to_string(output.join("SHA256SUMS"))?,
        format!("{digest}  {name}\n")
    );
    let audit: Value = storage::parse_json(&fs::read(output.join(&audit_name))?)?;
    assert_eq!(audit["appimage"]["sha256"], digest.as_str());
    let libraries = audit["bundled_libraries"]
        .as_array()
        .ok_or("audit lacks libraries")?;
    for package in ["libgtk-4-1", "libadwaita-1-0", "libvte-2.91-gtk4-0"] {
        assert!(
            libraries.iter().any(|record| record["package"] == package),
            "{package} is not recorded as bundled"
        );
    }
    assert!(audit["host_libraries"]
        .as_array()
        .is_some_and(|names| names.iter().any(|name| name == "libc.so.6")));
    assert!(
        libraries.iter().all(|record| record["path"]
            .as_str()
            .is_some_and(|path| !path.starts_with("usr/lib/gtk-4.0/"))),
        "unreachable GTK modules were bundled"
    );
    let sha = Command::new("/usr/bin/sha256sum")
        .args(["--check", "SHA256SUMS"])
        .current_dir(&output)
        .output()?;
    assert!(sha.status.success());
    let second = build(&output)?;
    assert!(!second.status.success());
    assert_eq!(storage::sha256(fs::File::open(&image)?)?, digest);
    fs::remove_dir_all(root)?;
    Ok(())
}

#[test]
fn unreachable_gtk_modules_and_typelibs_are_removed_and_odd_entries_refused() -> Result<()> {
    let root = scratch("among-appimage-modules")?;
    // Nothing to remove is not an error.
    appimage_build::remove_unreachable_modules(&root)?;
    write(
        &root,
        "usr/lib/gtk-4.0/4.0.0/printbackends/libprintbackend-file.so",
        ELF,
    )?;
    write(
        &root,
        "usr/lib/girepository-1.0/Gtk-4.0.typelib",
        b"typelib",
    )?;
    write(&root, "usr/lib/libgtk-4.so.1", ELF)?;
    appimage_build::remove_unreachable_modules(&root)?;
    assert!(!root.join("usr/lib/gtk-4.0").exists());
    assert!(!root.join("usr/lib/girepository-1.0").exists());
    assert!(root.join("usr/lib/libgtk-4.so.1").is_file());
    // A file or a link in place of the module directory is an unknown layout.
    write(&root, "usr/lib/gtk-4.0", b"not a directory")?;
    assert!(appimage_build::remove_unreachable_modules(&root).is_err());
    fs::remove_file(root.join("usr/lib/gtk-4.0"))?;
    std::os::unix::fs::symlink("/usr/lib", root.join("usr/lib/girepository-1.0"))?;
    assert!(appimage_build::remove_unreachable_modules(&root).is_err());
    fs::remove_dir_all(root)?;
    Ok(())
}
